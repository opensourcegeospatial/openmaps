/** Norwegian display name for a Nominatim/OSM type; undefined for unknown ones. */
export function translatePlaceType(type: unknown): string | undefined {
  if (typeof type !== 'string') return undefined;
  const key = type.trim().toLowerCase();
  if (!key) return undefined;
  return PLACE_TYPES[key];
}
